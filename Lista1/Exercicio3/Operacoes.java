public class Operacoes {
    public static void main(String[] args) {
        int Num1 = 10;
        int Num2 = 20;

        System.out.println("A Soma do numero 1 com o numero 2 multiplicado por 2  é " + ((Num1 + Num2) * 2));
        System.out.println("O resto da divisao entre o numero 1 e o numero 2 é " + (Num1%Num2));
        System.out.println("O resultado da divisao inteira entre o Numero 1 e o Numero 2 é " + (Num1/Num2));
    }
}
